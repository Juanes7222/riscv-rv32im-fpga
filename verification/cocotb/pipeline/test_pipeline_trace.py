"""Cycle-by-cycle trace of the five-stage pipeline.

The trace documents, cycle by cycle, how a program advances through the five
stages and how the hazard-resolution logic reacts.  It is the evidence
requested by the anteproyecto for the visualization module (Activity 4.2),
generated from the same RTL that is synthesized for the DE1-SoC.

Outputs:
    results/trace_pipeline.csv   - one row per clock cycle
    results/trace_pipeline.tex   - the same table, ready for the thesis

Usage:
    make -C verification/cocotb/pipeline TEST=test_pipeline_trace \\
         COCOTB_TEST_MODULES=test_pipeline_trace
"""

import os
import pathlib

import cocotb
from cocotb.clock import Clock
from cocotb.triggers import ReadOnly, RisingEdge

from conftest import reset_dut

REPO_ROOT = pathlib.Path(os.environ.get("REPO_ROOT", pathlib.Path(__file__).parents[3]))
RESULTS_DIR = REPO_ROOT / "results"

# The traced program: three dependent adds, a load-use pair and a taken
# branch, so the trace shows a forwarding case, a stall and a flush.
PROGRAM = [
    0x00500193,  # addi x3, x0, 5
    0x00318113,  # addi x2, x3, 3
    0x002081b3,  # add  x3, x1, x2
    0x00002103,  # lw   x2, 0(x0)
    0x002081b3,  # add  x3, x1, x2   (load-use: one stall)
    0x00210463,  # beq  x2, x2, +8    (taken branch)
    0x00100113,  # addi x2, x0, 1     (flushed)
    0x002081b3,  # add  x3, x1, x2    (branch target)
]

FIELDS = [
    "cycle", "if_pc", "if_instr", "id_pc", "id_instr", "ex_pc", "ex_instr",
    "mem_pc", "mem_instr", "wb_pc", "wb_instr", "stall", "load_use",
    "branch_flush", "flush",
]


def _hex(value) -> str:
    return f"0x{int(value):08x}"


async def _sample(dut) -> dict:
    return {
        "cycle": int(dut.u_perf.cycle_count.value),
        "if_pc": _hex(dut.if_pc.value),
        "if_instr": _hex(dut.if_instruction.value),
        "id_pc": _hex(dut.id_pc.value),
        "id_instr": _hex(dut.id_instruction.value),
        "ex_pc": _hex(dut.ex_pc.value),
        "ex_instr": _hex(dut.ex_instruction.value),
        "mem_pc": _hex(dut.mem_pc.value),
        "mem_instr": _hex(dut.mem_instruction.value),
        "wb_pc": _hex(dut.wb_pc.value),
        "wb_instr": _hex(dut.wb_instruction.value),
        "stall": int(dut.stall.value),
        "load_use": int(dut.load_use_hazard.value),
        "branch_flush": int(dut.branch_flush.value),
        "flush": int(dut.flush.value),
    }


def _latex(rows: list) -> str:
    header = " & ".join(f"\\texttt{{{f}}}" for f in FIELDS)
    lines = [
        "% Generated by verification/cocotb/pipeline/test_pipeline_trace.py",
        "\\begin{tabular}{" + "l" * len(FIELDS) + "}",
        "\\hline",
        header + " \\\\",
        "\\hline",
    ]
    for row in rows:
        cells = []
        for field in FIELDS:
            value = row[field]
            if field.endswith("_pc") or field.endswith("_instr"):
                cells.append(f"\\texttt{{{value[2:]}}}")
            else:
                cells.append(str(value))
        lines.append(" & ".join(cells) + " \\\\")
    lines += ["\\hline", "\\end{tabular}", ""]
    return "\n".join(lines)


@cocotb.test()
async def test_pipeline_trace(dut):
    """Run the program and record the state of every stage, cycle by cycle."""
    clock = Clock(dut.clk, 10, unit="ns")
    cocotb.start_soon(clock.start())

    for i, word in enumerate(PROGRAM):
        dut.u_imem.mem[i].value = word
    for i in range(len(PROGRAM), 64):
        dut.u_imem.mem[i].value = 0x00000013

    await reset_dut(dut)

    rows = []
    for _ in range(24):
        await RisingEdge(dut.clk)
        await ReadOnly()          # the state of the edge has settled
        rows.append(await _sample(dut))

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    csv_path = RESULTS_DIR / "trace_pipeline.csv"
    with open(csv_path, "w", newline="") as fp:
        fp.write(",".join(FIELDS) + "\n")
        for row in rows:
            fp.write(",".join(str(row[f]) for f in FIELDS) + "\n")

    tex_path = RESULTS_DIR / "trace_pipeline.tex"
    tex_path.write_text(_latex(rows))

    cocotb.log.info(f"Trace written to {csv_path} and {tex_path}")

    # The trace must show the pipeline filling up and the load-use stall.
    assert any(r["stall"] for r in rows), "no stall in the trace"
    assert any(r["branch_flush"] for r in rows), "no branch flush in the trace"
